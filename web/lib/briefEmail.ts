/** Renders a regional briefing (the region_briefing tool's output) as an email. Shared by
 *  /api/brief-email (one recipient, on request) and /api/dispatch (each zone's subscribers). */
const esc = (s: unknown) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]!));
const mw = (v: unknown) => (typeof v === "number" ? `${v.toLocaleString("en-US")} MW` : "n/a");

export type Brief = {
  region: string; date: string; grid_alert_level: string; forecast_peak_mw: number; peak_hour: number; peak_window: string;
  typical_peak_this_month_mw: number | null; vs_typical_pct: number | null; temp_high_f: number; temp_low_f: number;
  important: string[]; recommendations: string[]; actual_peak_mw?: number;
};

export function render(b: Brief, appUrl: string) {
  const colour = { ALERT: "#e6612a", WATCH: "#c9a227", NORMAL: "#1f8f88" }[b.grid_alert_level] ?? "#4f5f6f";
  const subject = `[${b.grid_alert_level}] ${b.region} briefing for ${b.date}: peak ${mw(b.forecast_peak_mw)}, ${b.peak_window}`;
  const rows: [string, string][] = [
    ["Forecast peak", `${mw(b.forecast_peak_mw)} around ${b.peak_hour}:00`],
    ["Busiest hours", b.peak_window],
    ["Typical peak this month", b.typical_peak_this_month_mw ? `${mw(b.typical_peak_this_month_mw)} (${b.vs_typical_pct! >= 0 ? "+" : ""}${b.vs_typical_pct}% today)` : "n/a"],
    ["Temperature", `high ${b.temp_high_f} °F, low ${b.temp_low_f} °F`],
    ["Grid-wide alert level", b.grid_alert_level],
  ];
  const text = [
    `${b.region} briefing for ${b.date}`, "", "What's important:", ...b.important.map((x) => `- ${x}`), "",
    "What to do:", ...b.recommendations.map((x) => `- ${x}`), "", ...rows.map(([k, v]) => `${k}: ${v}`), "",
    `Open the app: ${appUrl}/analyst`,
    "Generated by the ERCOT load forecasting project (ML 6302). Forecasts use observed weather for past days: decision support, not an official ERCOT forecast.",
  ].join("\n");
  const li = (xs: string[]) => xs.map((x) => `<li style="margin:4px 0">${esc(x)}</li>`).join("");
  const html = `<div style="font-family:Arial,Helvetica,sans-serif;max-width:580px;color:#13202e">
<div style="background:${colour};color:#fff;padding:12px 16px;font-weight:bold;font-size:16px">${esc(b.grid_alert_level)} · ${esc(b.region)} · ${esc(b.date)}</div>
<h3 style="margin:18px 0 6px">What's important</h3><ul style="padding-left:20px;margin:0">${li(b.important)}</ul>
<h3 style="margin:18px 0 6px">What to do</h3><ul style="padding-left:20px;margin:0">${li(b.recommendations)}</ul>
<table cellpadding="6" style="border-collapse:collapse;margin-top:16px;font-size:14px;width:100%">
${rows.map(([k, v]) => `<tr style="border-top:1px solid #d5dbe0"><td style="color:#4f5f6f">${esc(k)}</td><td style="text-align:right"><b>${esc(v)}</b></td></tr>`).join("")}
</table>
<p style="margin-top:18px"><a href="${esc(appUrl)}/analyst" style="color:#1c5ba6">Open the grid analyst</a></p>
<p style="color:#77818b;font-size:12px">Generated by the ERCOT load forecasting project (ML 6302). Forecasts use observed weather for past days: decision support, not an official ERCOT forecast.</p></div>`;
  return { subject, text, html };
}
